import Foundation

enum PasteboardTypes {
    static let plainText = "public.utf8-plain-text"
    static let rtf = "public.rtf"
    static let rtfd = "com.apple.flat-rtfd"
    static let html = "public.html"
    static let fileURL = "public.file-url"
    static let url = "public.url"

    static let imageTypes = ["public.png", "public.tiff", "public.jpeg"]

    /// Маркеры, которыми менеджеры паролей и другие приложения помечают
    /// приватное/временное содержимое (стандарт nspasteboard.org).
    static let privateMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Основные форматы, которые сохраняем всегда (до лимита размера).
    static let known: Set<String> = [
        plainText, "public.utf16-external-plain-text", rtf, rtfd, html,
        fileURL, url, "public.url-name", "public.png", "public.tiff", "public.jpeg",
        "com.adobe.pdf", "com.apple.webarchive",
    ]

    static let maxKnownTypeBytes = 50 * 1024 * 1024
    static let maxOtherTypeBytes = 1 * 1024 * 1024
    static let maxTotalBytes = 100 * 1024 * 1024

    static func shouldStore(type: String, size: Int) -> Bool {
        if type.hasPrefix("dyn.") || privateMarkers.contains(type) { return false }
        if known.contains(type) { return size <= maxKnownTypeBytes }
        return size <= maxOtherTypeBytes
    }

    /// Приложения, которые по умолчанию не записываются в историю.
    static let defaultIgnoredApps: [String] = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.agilebits.onepassword7",
        "com.1password.1password",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
        "com.lastpass.LastPass",
    ]
}
